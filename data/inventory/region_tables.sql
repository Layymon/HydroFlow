-- Bago East and Bago West keep the same classes in separate tables.

CREATE TABLE IF NOT EXISTS bago_east_balances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(40) NOT NULL,
    item_code VARCHAR(40),
    quantity NUMERIC(14, 2) NOT NULL DEFAULT 0,
    unit VARCHAR(20) NOT NULL,
    CONSTRAINT ck_bago_east_balance_nonnegative CHECK (quantity >= 0),
    CONSTRAINT ck_bago_east_fund_has_no_subclass CHECK (
        (category_code <> 'fund') OR (item_code IS NULL)
    ),
    CONSTRAINT ck_bago_east_subclass_required CHECK (
        (category_code = 'fund') OR (item_code IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_bago_east_balance_item
    ON bago_east_balances (category_code, item_code)
    WHERE item_code IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_bago_east_balance_fund
    ON bago_east_balances (category_code)
    WHERE item_code IS NULL;

CREATE TABLE IF NOT EXISTS bago_west_balances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(40) NOT NULL,
    item_code VARCHAR(40),
    quantity NUMERIC(14, 2) NOT NULL DEFAULT 0,
    unit VARCHAR(20) NOT NULL,
    CONSTRAINT ck_bago_west_balance_nonnegative CHECK (quantity >= 0),
    CONSTRAINT ck_bago_west_fund_has_no_subclass CHECK (
        (category_code <> 'fund') OR (item_code IS NULL)
    ),
    CONSTRAINT ck_bago_west_subclass_required CHECK (
        (category_code = 'fund') OR (item_code IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_bago_west_balance_item
    ON bago_west_balances (category_code, item_code)
    WHERE item_code IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_bago_west_balance_fund
    ON bago_west_balances (category_code)
    WHERE item_code IS NULL;

CREATE TABLE IF NOT EXISTS bago_east_movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(40) NOT NULL,
    item_code VARCHAR(40),
    direction VARCHAR(10) NOT NULL,
    entry_mode VARCHAR(20) NOT NULL,
    quantity NUMERIC(14, 2) NOT NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_bago_east_movement_quantity CHECK (quantity > 0),
    CONSTRAINT ck_bago_east_movement_direction CHECK (direction IN ('in', 'out')),
    CONSTRAINT ck_bago_east_movement_entry_mode CHECK (entry_mode IN ('manual', 'scan')),
    CONSTRAINT ck_bago_east_fund_manual_only CHECK (
        (category_code <> 'fund') OR (entry_mode = 'manual' AND item_code IS NULL)
    ),
    CONSTRAINT ck_bago_east_movement_subclass_required CHECK (
        (category_code = 'fund') OR (item_code IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS bago_west_movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(40) NOT NULL,
    item_code VARCHAR(40),
    direction VARCHAR(10) NOT NULL,
    entry_mode VARCHAR(20) NOT NULL,
    quantity NUMERIC(14, 2) NOT NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_bago_west_movement_quantity CHECK (quantity > 0),
    CONSTRAINT ck_bago_west_movement_direction CHECK (direction IN ('in', 'out')),
    CONSTRAINT ck_bago_west_movement_entry_mode CHECK (entry_mode IN ('manual', 'scan')),
    CONSTRAINT ck_bago_west_fund_manual_only CHECK (
        (category_code <> 'fund') OR (entry_mode = 'manual' AND item_code IS NULL)
    ),
    CONSTRAINT ck_bago_west_movement_subclass_required CHECK (
        (category_code = 'fund') OR (item_code IS NOT NULL)
    )
);

INSERT INTO bago_east_balances (category_code, item_code, quantity, unit)
SELECT category.code, item.code, 0, item.unit
FROM inventory_categories AS category
JOIN inventory_item_types AS item ON item.category_id = category.id
WHERE NOT EXISTS (
    SELECT 1 FROM bago_east_balances AS existing
    WHERE existing.category_code = category.code AND existing.item_code = item.code
);

INSERT INTO bago_west_balances (category_code, item_code, quantity, unit)
SELECT category.code, item.code, 0, item.unit
FROM inventory_categories AS category
JOIN inventory_item_types AS item ON item.category_id = category.id
WHERE NOT EXISTS (
    SELECT 1 FROM bago_west_balances AS existing
    WHERE existing.category_code = category.code AND existing.item_code = item.code
);

INSERT INTO bago_east_balances (category_code, item_code, quantity, unit)
SELECT 'fund', NULL, 0, 'mmk'
WHERE NOT EXISTS (
    SELECT 1 FROM bago_east_balances WHERE category_code = 'fund' AND item_code IS NULL
);

INSERT INTO bago_west_balances (category_code, item_code, quantity, unit)
SELECT 'fund', NULL, 0, 'mmk'
WHERE NOT EXISTS (
    SELECT 1 FROM bago_west_balances WHERE category_code = 'fund' AND item_code IS NULL
);
